#!/usr/bin/env python3
"""Emit the TLE admin role-reconciliation ConfigMap from a role manifest.

Usage: python3 generate.py <role-manifest.json> [tle-admin-role-reconciliation.yaml]

The manifest is deployment information published by the TLE server repository.
Regenerate the checked-in ConfigMap whenever the vendored manifest changes.
"""

import json
import sys
import textwrap
from pathlib import Path


if len(sys.argv) not in (2, 3):
    sys.exit(__doc__.split("\n\n")[1])

manifest_path = Path(sys.argv[1])
out = (Path(sys.argv[2]) if len(sys.argv) == 3 else
       Path(__file__).parents[1] / "config/tle-admin-role-reconciliation.yaml")
manifest = json.loads(manifest_path.read_text(encoding="utf-8"))

capabilities = "\n".join(
    f"{capability['name']}|TLE capability ({'+'.join(capability['access'])}): "
    f"{', '.join(capability['tools'])}"
    for capability in manifest["capabilities"]
)
bundles = "\n".join(
    f"{composite['name']}|{composite['description']}"
    for composite in manifest["composites"]
)
members = "\n".join(
    f"{composite['name']}|{name}"
    for composite in manifest["composites"]
    for name in composite["capabilities"]
)
for value in (capabilities, bundles, members):
    assert "'" not in value, "single quote would break the shell literal"

summary = ", ".join(
    f"{composite['name']}={len(composite['capabilities'])}"
    for composite in manifest["composites"]
)

script = f'''#!/bin/sh
# Reconcile TLE admin client roles in the Keycloak "homelab" realm.
#
# Generated by generate.py from The Last Exam's role manifest
#   (manifest_version {manifest['manifest_version']}, registry schema {manifest['registry_schema_version']},
#    {len(manifest['capabilities'])} capabilities, composites: {summary}).
# Do not edit this file by hand; regenerate it from the vendored manifest.
#
# This script owns roles and role-composite membership on exactly
# tle-admin-dev and tle-admin-prod. It never reads or mutates realm roles,
# users, groups, realm settings, default realm roles, or another client.
set -eu

: "${{KC_ADMIN_USERNAME:?missing admin username}}"
: "${{KC_CLI_PASSWORD:?missing admin password}}"
: "${{TLE_ADMIN_CLIENT_IDS:?missing TLE admin client IDs}}"
KCADM=${{KCADM:-/opt/keycloak/bin/kcadm.sh}}
JQ=${{JQ:-/tools/jq}}
REALM=homelab
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

if [ "$TLE_ADMIN_CLIENT_IDS" != "tle-admin-dev tle-admin-prod" ]; then
  echo "unexpected TLE admin client allowlist" >&2
  exit 2
fi

CAPABILITIES='
{capabilities}
'
BUNDLES='
{bundles}
'
MEMBERS='
{members}
'

lines() {{ printf '%s\\n' "$1" | grep -v '^$'; }}

"$KCADM" config credentials \\
  --server http://keycloak.keycloak.svc.cluster.local:8080 \\
  --realm master --user "$KC_ADMIN_USERNAME" \\
  --config "$WORK/kcadm.config" >/dev/null

kc() {{ "$KCADM" "$@" -r "$REALM" --config "$WORK/kcadm.config"; }}
client_uuid() {{
  client_id=$1
  clients=$(kc get clients -q "clientId=$client_id" --fields id,clientId)
  printf '%s' "$clients" | "$JQ" -er --arg client_id "$client_id" '
    [.[] | select(.clientId == $client_id)] |
    if length == 1 then .[0].id
    elif length == 0 then error("missing client ID: " + $client_id)
    else error("duplicate client ID: " + $client_id) end'
}}
role_names() {{ kc get "clients/$1/roles" | "$JQ" -r '.[].name' | sort; }}
role_json() {{ kc get "clients/$1/roles/$2"; }}
composite_names() {{
  kc get "clients/$1/roles/$2/composites" | "$JQ" -r '.[].name' | sort
}}
ensure_role() {{
  client_uuid=$1 role_name=$2 description=$3
  if grep -Fxq "$role_name" "$WORK/have-roles"; then return; fi
  "$JQ" -n --arg name "$role_name" --arg description "$description" \\
    '{{name: $name, description: $description}}' |
    kc create "clients/$client_uuid/roles" -f - >/dev/null
}}
ensure_composite_member() {{
  client_uuid=$1 bundle=$2 member=$3
  if grep -Fxq "$member" "$WORK/have-$bundle"; then return; fi
  role_json "$client_uuid" "$member" > "$WORK/member.json"
  "$JQ" -s '.' "$WORK/member.json" |
    kc create "clients/$client_uuid/roles/$bundle/composites" -f - >/dev/null
}}
delete_composite_member() {{
  client_uuid=$1 bundle=$2 member=$3
  role_json "$client_uuid" "$member" > "$WORK/member.json"
  "$JQ" -s '.' "$WORK/member.json" |
    kc delete "clients/$client_uuid/roles/$bundle/composites" -f - >/dev/null
}}
reconcile_client() {{
  client_id=$1
  client_uuid=$(client_uuid "$client_id")
  lines "$CAPABILITIES" | cut -d'|' -f1 | sort > "$WORK/want-capabilities"
  lines "$BUNDLES" | cut -d'|' -f1 | sort > "$WORK/want-bundles"
  sort "$WORK/want-capabilities" "$WORK/want-bundles" > "$WORK/want-roles"
  role_names "$client_uuid" > "$WORK/have-roles"

  {{ lines "$CAPABILITIES"; lines "$BUNDLES"; }} |
    while IFS='|' read -r name description; do
      ensure_role "$client_uuid" "$name" "$description"
    done

  while IFS= read -r bundle; do
    lines "$MEMBERS" | awk -F'|' -v bundle="$bundle" '$1 == bundle {{print $2}}' |
      sort > "$WORK/want-$bundle"
    composite_names "$client_uuid" "$bundle" > "$WORK/have-$bundle"
    while IFS= read -r member; do
      [ -n "$member" ] || continue
      ensure_composite_member "$client_uuid" "$bundle" "$member"
    done < "$WORK/want-$bundle"
    composite_names "$client_uuid" "$bundle" > "$WORK/have-$bundle"
    grep -Fxv -f "$WORK/want-$bundle" "$WORK/have-$bundle" > "$WORK/stale-$bundle" || true
    while IFS= read -r member; do
      [ -n "$member" ] || continue
      delete_composite_member "$client_uuid" "$bundle" "$member"
    done < "$WORK/stale-$bundle"
  done < "$WORK/want-bundles"

  role_names "$client_uuid" > "$WORK/have-roles"
  grep -Fxv -f "$WORK/want-roles" "$WORK/have-roles" > "$WORK/stale-roles" || true
  while IFS= read -r name; do
    [ -n "$name" ] || continue
    kc delete "clients/$client_uuid/roles/$name" >/dev/null
  done < "$WORK/stale-roles"

  role_names "$client_uuid" > "$WORK/have-roles"
  cmp -s "$WORK/want-roles" "$WORK/have-roles" || {{
    echo "$client_id roles differ from manifest" >&2
    exit 1
  }}
  while IFS= read -r bundle; do
    composite_names "$client_uuid" "$bundle" > "$WORK/have-$bundle"
    cmp -s "$WORK/want-$bundle" "$WORK/have-$bundle" || {{
      echo "$client_id composite $bundle differs from manifest" >&2
      exit 1
    }}
  done < "$WORK/want-bundles"
}}

for client_id in $TLE_ADMIN_CLIENT_IDS; do
  reconcile_client "$client_id"
done
'''

document = """apiVersion: v1
kind: ConfigMap
metadata:
  name: keycloak-tle-admin-role-reconciliation
  namespace: keycloak
data:
  reconcile-tle-admin-roles.sh: |
""" + textwrap.indent(script, "    ")
out.write_text(document, encoding="utf-8")
print(f"wrote {out}")
